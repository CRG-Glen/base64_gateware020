#!/usr/bin/env python3
"""Turn the fx68k build's Diamond LPF into one nextpnr-ecp5 accepts.

nextpnr reads LOCATE COMP, IOBUF PORT and FREQUENCY. It does not know port
groups, MULTICYCLE, BLOCK, SYSCONFIG or Reveal aliases. Groups are expanded
into one IOBUF PORT per member; the rest is dropped (SYSCONFIG's SPI
settings become ecppack options in the build script instead)."""
import fnmatch, re, sys
src, dst = sys.argv[1], sys.argv[2]
lines = open(src).read().splitlines()
ports, groups, out = [], {}, []
for l in lines:
    m = re.match(r'\s*LOCATE\s+COMP\s+"([^"]+)"', l)
    if m: ports.append(m.group(1))
for l in lines:
    m = re.match(r'\s*DEFINE\s+PORT\s+GROUP\s+"([^"]+)"\s+"([^"]+)"', l)
    if m: groups[m.group(1)] = [p for p in ports if fnmatch.fnmatch(p, m.group(2))]
out.append('# Generated by scripts/lpf_for_nextpnr.py from base64_diamond.lpf')
out.append('# (the fx68k build\'s constraints). Edit the source, not this file.')
for l in lines:
    s = l.strip()
    if re.match(r'(rvl_alias|BLOCK|SYSCONFIG|MULTICYCLE|DEFINE\s+PORT)', s):
        out.append('# [dropped] ' + s); continue
    m = re.match(r'IOBUF\s+GROUP\s+"([^"]+)"\s+(.*);', s)
    if m:
        out.append('# [expanded] ' + s)
        for p in groups[m.group(1)]:
            out.append('IOBUF PORT "%s" %s;' % (p, m.group(2)))
        continue
    out.append(l)
out.append('FREQUENCY PORT "clk_12x" 86.0 MHz;')
open(dst, 'w').write('\n'.join(out) + '\n')
print('%s: %d pins, groups %s' % (dst, len(ports), {k: len(v) for k, v in groups.items()}))
