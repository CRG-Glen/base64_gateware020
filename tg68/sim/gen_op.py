def asm():
    o = []
    w = o.append
    w('| generated by gen_op.py: do not edit')
    w('        .org 0\n        .long 0x00009000\n        .long start\n        .org 0x100')
    w('start:  moveq   #1,%d0\n        movec   %d0,%cacr')
    w('        lea     code,%a0\n        lea     0x08004000,%a1\n        move.w  #(codeend-code)/4,%d0')
    w('cp:     move.l  (%a0)+,(%a1)+\n        dbra    %d0,cp')
    w('        jsr     0x08004000\n        move.b  #1,0x8F00\n        jsr     0x08004000\n        move.b  #2,0x8F00')
    w('        move.l  #0x7F80,0x8100\n        move.l  #0x600DC0DE,0x8FF0\ndone:   bra.s   done')
    w('        .balign 4\ncode:   move.l  %sp,%a4\n        lea     0x08030800,%sp')
    w('        lea     0x08020100,%a0\n        lea     0x08010000,%a5\n        lea     retfn(%pc),%a2')
    w('        move.l  #0x7FFF,%d2\n        moveq   #17,%d3\n        move.l  #0x12345678,%d6\n        move.l  %d6,%d1')
    for name, lines, setup in T:
        w('        move.w  %d0,(%a5)           | ' + name)
        if lines == ['LOOP']:
            w('        moveq   #%d,%%d4\n1:      dbra    %%d4,1b' % (REPS - 1))
            continue
        for i in range(REPS):
            for l in lines:
                w(('' if l[0].isdigit() else '        ') + l)
    w('        move.w  %d0,(%a5)\n        move.l  %a4,%sp\n        rts\nretfn:  rts\n        .balign 4\ncodeend:')
    open('test_op.s', 'w').write('\n'.join(o) + '\n')
def report():
    m = [l.split()[1:] for l in sys.stdin if l.startswith('OPMARK')]
    n = len(T) + 1
    if len(m) != 2 * n:
        print('bench op: expected %d markers, saw %d' % (2 * n, len(m))); sys.exit(1)
    m = [(int(c), int(s)) for _, c, s in m[n:]]
    d = {}
    for i, (name, lines, setup) in enumerate(T):
        d[name] = (m[i + 1][0] - m[i][0], m[i + 1][1] - m[i][1])
    e = d['(empty)']
    print('marker to marker with nothing between: %d clocks, %d steps' % e)
    print('%-28s %8s %8s' % ('per instruction', 'clocks', 'steps'))
    for name, lines, setup in T[1:]:
        c, s = d[name][0] - e[0], d[name][1] - e[1]
        if setup:
            c -= d[setup][0] - e[0]; s -= d[setup][1] - e[1]
        print('%-28s %8.2f %8.2f' % (name, c / REPS, s / REPS))
if sys.argv[1:] == ['asm']: asm()
else: report()
